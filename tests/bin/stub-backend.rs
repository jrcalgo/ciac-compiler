//! v0.8 external-backend protocol M2: a stub `ciac-backend-<name>`
//! executable used only by `tests/tests/external_backend.rs`, so those
//! tests stay hermetic to the Rust toolchain (no assumption that
//! python3/etc. exist on the test runner). Behavior is switched by the
//! request's own `project_name` field (not an env var — mutating
//! process-wide env vars from a multi-threaded `cargo test` binary
//! requires `unsafe`, which this workspace forbids outright) so one
//! binary covers every scenario `ciac_codegen::external::ExternalBackend`
//! needs to handle:
//!
//! - `echo` (default, including no `project_name` at all): reads the
//!   real request, writes back a valid response whose one file embeds
//!   the request's `target` — proving the round trip carries real
//!   data, not just "doesn't crash".
//! - `fail`: writes a message to stderr, exits 1.
//! - `garbage`: writes non-JSON to stdout, exits 0.
//! - `bad-version`: writes an otherwise-valid response claiming
//!   `protocol_version: 999`.
//!
//! Reading the mode requires parsing the request first in every case
//! (unlike the old env-var design), which is fine — every mode below
//! still gets a real request on stdin to consume.

use ciac_codegen::protocol::{CodegenRequest, CodegenResponse, ResponseFile};
use ciac_codegen::FileRole;
use std::io::{Read, Write};

fn main() {
    let mut input = String::new();
    std::io::stdin()
        .read_to_string(&mut input)
        .expect("read stdin");
    let request: CodegenRequest = serde_json::from_str(&input).expect("valid request");
    let mode = request
        .project_name
        .clone()
        .unwrap_or_else(|| "echo".to_owned());

    match mode.as_str() {
        "fail" => {
            eprintln!("stub-backend: intentional failure for testing");
            std::process::exit(1);
        }
        "garbage" => {
            print!("this is not json {{{{");
            std::process::exit(0);
        }
        "bad-version" => {
            let response = CodegenResponse {
                protocol_version: 999,
                files: Vec::new(),
                notes: Vec::new(),
            };
            print!("{}", serde_json::to_string(&response).unwrap());
        }
        "echo" => {
            let response = CodegenResponse {
                protocol_version: ciac_codegen::protocol::PROTOCOL_VERSION,
                files: vec![ResponseFile {
                    path: "stub-output.txt".to_owned(),
                    content: format!("generated for target: {}", request.target),
                    role: FileRole::Owned,
                }],
                notes: vec!["generated by stub-backend".to_owned()],
            };
            let out = serde_json::to_string(&response).unwrap();
            std::io::stdout().write_all(out.as_bytes()).unwrap();
        }
        other => {
            eprintln!("stub-backend: unknown mode `{other}` (from project_name)");
            std::process::exit(2);
        }
    }
}
